-- Chuẩn hóa số tờ/số thửa lấy từ Google Sheet (kiểu text, có thể dính
-- khoảng trắng, số 0 ở đầu, hoặc đuôi ".0" do Sheets xuất số) về đúng
-- dạng số nguyên dạng text, để so khớp được với so_to/so_thua kiểu
-- integer bên bảng thua_dat. Giữ nguyên (chỉ trim) nếu không phải số,
-- vì madvhc là mã đơn vị hành chính — số 0 ở đầu có ý nghĩa, không được
-- chuẩn hóa qua hàm này.
create or replace function public.normalize_so_text(p_value text)
returns text
language plpgsql
immutable
as $$
declare
  v text := trim(coalesce(p_value, ''));
begin
  if v = '' then
    return null;
  end if;

  if v ~ '^[0-9]+(\.[0-9]+)?$' then
    return trunc(v::numeric)::bigint::text;
  end if;

  return v;
end;
$$;

