-- Bảng dữ liệu GCN đồng bộ từ Google Sheet.
-- CHỈ thêm bảng mới, không đụng tới thua_dat/dong_bo_du_lieu hay bất kỳ
-- bảng WebGIS nào khác. Chạy file này trong Supabase SQL Editor của
-- project WebGIS hiện tại (không tạo project Supabase mới).

create table if not exists public.du_lieu_gcn (
  id bigint generated by default as identity primary key,

  -- Thông tin nguồn (khớp 1 dòng trong danh_sach_sheet.xlsx).
