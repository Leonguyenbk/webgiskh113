  drop column if exists ngaysinh_chusudunghientai;

-- Khóa ghép madvhc + số tờ + số thửa (đã chuẩn hóa) để đối chiếu 1-1 với
-- (ma_xa, so_to, so_thua) bên bảng thua_dat — dùng kiểm tra thửa nào đã
-- có dữ liệu GCN (xem get_parcels_in_view/search_parcels trong
-- supabase/schema.sql).
alter table public.du_lieu_gcn
  add column if not exists madvhc_soto_sothua text
  generated always as (
    trim(coalesce(madvhc, ''))
    || '_' || coalesce(public.normalize_so_text(soto), '')
    || '_' || coalesce(public.normalize_so_text(sothua), '')
  ) stored;

