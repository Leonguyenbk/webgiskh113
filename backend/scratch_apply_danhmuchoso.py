"""Áp trực tiếp lên DB: cột dong_bo_du_lieu.so_gcn_mplis (GCN từ MPLIS sync)
+ bảng danhmuchoso + các hàm danhmuchoso_kiem_tra_gcn/them/list, khớp
supabase/schema.sql. Chạy 1 lần."""
from __future__ import annotations

import sys

import psycopg2

from app.config import Config

SQL = r"""
alter table public.dong_bo_du_lieu
    add column if not exists so_gcn_mplis text;

create or replace function public.batch_upsert_dong_bo_du_lieu(p_rows jsonb)
returns table (ma_xa text, so_to integer, so_thua integer, was_insert boolean)
language sql
as $$
    insert into public.dong_bo_du_lieu as d (
        ma_xa, so_to, so_thua,
        da_xuat_so_dia_chinh_dien_tu, chua_xuat_so_dia_chinh_dien_tu,
        dong_bo_3_khoi, khong_dong_bo_3_khoi,
        chi_co_du_lieu_thuoc_tinh,
        khop_csdlqg_dan_cu, chua_khop_csdlqg_dan_cu, khong_xac_dinh_csdlqg_dan_cu,
        van_hanh_24_7, khong_van_hanh_24_7,
        phan_loai_ke_hoach_2959,
        so_gcn_mplis
    )
    select
        i.value->>'ma_xa',
        (i.value->>'so_to')::integer,
        (i.value->>'so_thua')::integer,
        (i.value->>'da_xuat_so_dia_chinh_dien_tu')::boolean,
        (i.value->>'chua_xuat_so_dia_chinh_dien_tu')::boolean,
        (i.value->>'dong_bo_3_khoi')::boolean,
        (i.value->>'khong_dong_bo_3_khoi')::boolean,
        (i.value->>'chi_co_du_lieu_thuoc_tinh')::boolean,
        (i.value->>'khop_csdlqg_dan_cu')::boolean,
        (i.value->>'chua_khop_csdlqg_dan_cu')::boolean,
        (i.value->>'khong_xac_dinh_csdlqg_dan_cu')::boolean,
        (i.value->>'van_hanh_24_7')::boolean,
        (i.value->>'khong_van_hanh_24_7')::boolean,
        i.value->>'phan_loai_ke_hoach_2959',
        i.value->>'so_gcn_mplis'
    from jsonb_array_elements(p_rows) as i(value)
    on conflict (ma_xa, so_to, so_thua) do update set
        da_xuat_so_dia_chinh_dien_tu = excluded.da_xuat_so_dia_chinh_dien_tu,
        chua_xuat_so_dia_chinh_dien_tu = excluded.chua_xuat_so_dia_chinh_dien_tu,
        dong_bo_3_khoi = excluded.dong_bo_3_khoi,
        khong_dong_bo_3_khoi = excluded.khong_dong_bo_3_khoi,
        chi_co_du_lieu_thuoc_tinh = excluded.chi_co_du_lieu_thuoc_tinh,
        khop_csdlqg_dan_cu = excluded.khop_csdlqg_dan_cu,
        chua_khop_csdlqg_dan_cu = excluded.chua_khop_csdlqg_dan_cu,
        khong_xac_dinh_csdlqg_dan_cu = excluded.khong_xac_dinh_csdlqg_dan_cu,
        van_hanh_24_7 = excluded.van_hanh_24_7,
        khong_van_hanh_24_7 = excluded.khong_van_hanh_24_7,
        phan_loai_ke_hoach_2959 = excluded.phan_loai_ke_hoach_2959,
        so_gcn_mplis = excluded.so_gcn_mplis,
        updated_at = now()
    returning d.ma_xa, d.so_to, d.so_thua, (xmax = 0) as was_insert;
$$;

create table if not exists public.danhmuchoso (
    id bigint generated by default as identity primary key,
    nam integer,
    cap text,
    so_tt_ho_so text,
    ten_nguoi_su_dung_dat text,
    thua_dat_so_moi text,
    ban_do_so_moi text,
    thua_dat_so_cu text,
    ban_do_so_cu text,
    dia_chi_thua_dat text,
    so_seri_gcn text not null,
    loai_ho_so text,
    ghi_chu text,
    tao_luc timestamptz not null default now(),
    constraint danhmuchoso_so_seri_gcn_key unique (so_seri_gcn)
);
alter table public.danhmuchoso enable row level security;

create index if not exists idx_danhmuchoso_nam on public.danhmuchoso (nam);

create or replace function public.danhmuchoso_kiem_tra_gcn(p_so_seri_gcn text)
returns jsonb
language sql
stable
security definer
set search_path = public, extensions
as $$
    with gcn as (select trim(coalesce(p_so_seri_gcn, '')) as g)
    select jsonb_build_object(
        'da_nhap_form_nhom4', exists (
            select 1 from public.du_lieu_gcn x, gcn where trim(x.sophathanhgcn) = gcn.g and gcn.g <> ''
        ),
        'da_dong_bo_mplis', exists (
            select 1 from public.dong_bo_du_lieu x, gcn where trim(x.so_gcn_mplis) = gcn.g and gcn.g <> ''
        ),
        'da_co_trong_danh_muc', exists (
            select 1 from public.danhmuchoso x, gcn where trim(x.so_seri_gcn) = gcn.g and gcn.g <> ''
        )
    ) || jsonb_build_object(
        'ton_tai', (
            exists (select 1 from public.du_lieu_gcn x, gcn where trim(x.sophathanhgcn) = gcn.g and gcn.g <> '')
            or exists (select 1 from public.dong_bo_du_lieu x, gcn where trim(x.so_gcn_mplis) = gcn.g and gcn.g <> '')
            or exists (select 1 from public.danhmuchoso x, gcn where trim(x.so_seri_gcn) = gcn.g and gcn.g <> '')
        )
    );
$$;

revoke all on function public.danhmuchoso_kiem_tra_gcn(text) from public;
grant execute on function public.danhmuchoso_kiem_tra_gcn(text) to service_role;

create or replace function public.danhmuchoso_them(
    p_nam integer,
    p_cap text,
    p_so_tt_ho_so text,
    p_ten_nguoi_su_dung_dat text,
    p_thua_dat_so_moi text,
    p_ban_do_so_moi text,
    p_thua_dat_so_cu text,
    p_ban_do_so_cu text,
    p_dia_chi_thua_dat text,
    p_so_seri_gcn text,
    p_loai_ho_so text,
    p_ghi_chu text
)
returns public.danhmuchoso
language sql
security definer
set search_path = public, extensions
as $$
    insert into public.danhmuchoso (
        nam, cap, so_tt_ho_so, ten_nguoi_su_dung_dat,
        thua_dat_so_moi, ban_do_so_moi, thua_dat_so_cu, ban_do_so_cu,
        dia_chi_thua_dat, so_seri_gcn, loai_ho_so, ghi_chu
    ) values (
        p_nam, p_cap, p_so_tt_ho_so, p_ten_nguoi_su_dung_dat,
        p_thua_dat_so_moi, p_ban_do_so_moi, p_thua_dat_so_cu, p_ban_do_so_cu,
        p_dia_chi_thua_dat, trim(p_so_seri_gcn), p_loai_ho_so, p_ghi_chu
    )
    returning *;
$$;

revoke all on function public.danhmuchoso_them(
    integer, text, text, text, text, text, text, text, text, text, text, text
) from public;
grant execute on function public.danhmuchoso_them(
    integer, text, text, text, text, text, text, text, text, text, text, text
) to service_role;

create or replace function public.danhmuchoso_list(
    p_limit integer default 100,
    p_offset integer default 0,
    p_keyword text default null,
    p_nam integer default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
    v_total integer;
    v_items jsonb;
    v_kw text := '%' || coalesce(trim(p_keyword), '') || '%';
begin
    select count(*) into v_total
    from public.danhmuchoso d
    where (p_nam is null or d.nam = p_nam)
      and (
          p_keyword is null or trim(p_keyword) = ''
          or d.ten_nguoi_su_dung_dat ilike v_kw
          or d.so_seri_gcn ilike v_kw
          or d.so_tt_ho_so ilike v_kw
          or d.cap ilike v_kw
      );

    select coalesce(jsonb_agg(row_to_json(y)), '[]'::jsonb) into v_items
    from (
        select d.*
        from public.danhmuchoso d
        where (p_nam is null or d.nam = p_nam)
          and (
              p_keyword is null or trim(p_keyword) = ''
              or d.ten_nguoi_su_dung_dat ilike v_kw
              or d.so_seri_gcn ilike v_kw
              or d.so_tt_ho_so ilike v_kw
              or d.cap ilike v_kw
          )
        order by d.id desc
        limit p_limit offset p_offset
    ) y;

    return jsonb_build_object('total', v_total, 'items', v_items);
end;
$$;

revoke all on function public.danhmuchoso_list(integer, integer, text, integer) from public;
grant execute on function public.danhmuchoso_list(integer, integer, text, integer) to service_role;
"""


def main():
    conn = psycopg2.connect(Config.DATABASE_URL)
    cur = conn.cursor()
    print("Áp schema danhmuchoso + so_gcn_mplis...")
    cur.execute(SQL)
    conn.commit()
    print("Xong.")

    cur.execute("select count(*) from public.danhmuchoso")
    print("danhmuchoso rows:", cur.fetchone()[0])
    cur.close()
    conn.close()


if __name__ == "__main__":
    sys.exit(main())
