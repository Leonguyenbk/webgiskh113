          p_nhom is null or array_length(p_nhom, 1) is null
          or (
              'DEFAULT' = any(p_nhom)
              and (d.id is null or coalesce(trim(d.phan_loai_ke_hoach_2959), '') = '')
          )
          or upper(trim(d.phan_loai_ke_hoach_2959)) in (
              select upper(trim(x)) from unnest(p_nhom) as x
