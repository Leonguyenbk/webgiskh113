-- BẢN ĐỒ NỀN (tờ bản đồ dạng raster) — quản lý theo từng tờ (ma_xa +
-- so_to). KHÔNG xử lý DGN/KMZ/raster gì trên WebGIS/Render — toàn bộ việc
-- đọc KMZ (MicroStation xuất từ DGN), georeference, reproject EPSG:3857,
-- sinh tile XYZ và upload lên Supabase Storage do 1 Tool desktop Windows
-- riêng làm (xem d:\Python\ban-do-nen-tool\, ngoài repo này). WebGIS chỉ
-- nhận đăng ký qua RPC register_ban_do_nen (POST /api/ban-do-nen/register)
-- SAU KHI Tool đã upload xong 100% tile — geom ghi qua RPC vì PostgREST
-- không tự chuyển GeoJSON (jsonb) thành cột geometry; bbox_* chỉ là cache
-- hiển thị suy từ geom bằng trigger, lọc viewport dùng thẳng geom && (đã
-- có GIST index).
-- =========================================================

create table if not exists public.ban_do_nen (
    id bigint generated by default as identity primary key,
    ma_xa text not null,
    so_to integer not null,
    geom extensions.geometry(Polygon, 4326) not null,
    bbox_min_x double precision,
    bbox_min_y double precision,
    bbox_max_x double precision,
    bbox_max_y double precision,
    tile_url text not null,
    tile_version integer not null default 1,
    min_zoom integer,
    max_zoom integer,
    ghi_chu text,
    trang_thai text not null default 'ready',
    kich_hoat boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ban_do_nen_ma_xa_so_to_key unique (ma_xa, so_to)
);

create index if not exists ban_do_nen_geom_idx
    on public.ban_do_nen using gist (geom);
create index if not exists ban_do_nen_ma_xa_idx
    on public.ban_do_nen (ma_xa);

alter table public.ban_do_nen enable row level security;

-- Không tạo policy nào: chỉ Service Role Key (backend Flask) đọc/ghi
-- được bảng này, giống nguon_gcn/ranh_gioi_thon.

-- Suy bbox_* từ geom mỗi lần insert/update geom — chỉ để cache hiển thị
-- số liệu trên trang quản trị, KHÔNG dùng để lọc (lọc viewport dùng thẳng
-- geom && ở get_ban_do_nen_in_view).
create or replace function public.ban_do_nen_set_bbox_from_geom()
returns trigger
language plpgsql
as $$
begin
    new.bbox_min_x := ST_XMin(new.geom);
    new.bbox_min_y := ST_YMin(new.geom);
    new.bbox_max_x := ST_XMax(new.geom);
    new.bbox_max_y := ST_YMax(new.geom);
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists trg_ban_do_nen_set_geom on public.ban_do_nen;
drop trigger if exists trg_ban_do_nen_set_bbox_from_geom on public.ban_do_nen;
create trigger trg_ban_do_nen_set_bbox_from_geom
    before insert or update of geom
    on public.ban_do_nen
    for each row execute function public.ban_do_nen_set_bbox_from_geom();

-- API duy nhất mà Tool Windows gọi để hoàn tất đăng ký 1 tờ — CHỈ gọi sau
-- khi Tool đã upload xong 100% tile lên Storage (WebGIS không tự biết
-- tiến độ upload, tin tưởng Tool chỉ gọi khi đã xong). Upsert theo
-- (ma_xa, so_to): tờ đã có thì cập nhật geom/tile_url/tile_version mới
-- (đúng chiều tăng tile_version mỗi lần Tool xử lý lại — cache-busting).
create or replace function public.register_ban_do_nen(
    p_ma_xa text,
    p_so_to integer,
    p_geom_geojson jsonb,
    p_tile_url text,
    p_tile_version integer,
    p_min_zoom integer default null,
    p_max_zoom integer default null,
    p_ghi_chu text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    result_id bigint;
begin
    insert into public.ban_do_nen (
        ma_xa, so_to, geom, tile_url, tile_version, min_zoom, max_zoom, ghi_chu, trang_thai
    ) values (
        p_ma_xa, p_so_to,
        ST_SetSRID(ST_GeomFromGeoJSON(p_geom_geojson::text), 4326),
        p_tile_url, p_tile_version, p_min_zoom, p_max_zoom, p_ghi_chu, 'ready'
    )
    on conflict (ma_xa, so_to) do update set
        geom = excluded.geom,
        tile_url = excluded.tile_url,
        tile_version = excluded.tile_version,
        min_zoom = excluded.min_zoom,
        max_zoom = excluded.max_zoom,
        ghi_chu = coalesce(excluded.ghi_chu, public.ban_do_nen.ghi_chu),
        trang_thai = 'ready',
        updated_at = now()
    returning id into result_id;
    return result_id;
end;
$$;

revoke all on function public.register_ban_do_nen(text, integer, jsonb, text, integer, integer, integer, text) from public;
grant execute on function public.register_ban_do_nen(text, integer, jsonb, text, integer, integer, integer, text) to service_role;

-- Lấy các tờ bản đồ giao khung nhìn hiện tại — dùng cho tile loader
-- (viewport) và lớp ranh+nhãn trên bản đồ chính. Mặc định chỉ trả tờ đã
-- 'ready' và đang kich_hoat; p_include_all=true dùng cho trang quản trị.
create or replace function public.get_ban_do_nen_in_view(
    p_west double precision,
    p_south double precision,
    p_east double precision,
    p_north double precision,
    p_include_all boolean default false
)
returns jsonb
language sql
stable
security definer
set search_path = public, extensions
as $$
    select jsonb_build_object(
        'type', 'FeatureCollection',
        'features', coalesce(jsonb_agg(feature), '[]'::jsonb)
    )
    from (
        select jsonb_build_object(
            'type', 'Feature',
            'id', b.id,
            'geometry', ST_AsGeoJSON(b.geom)::jsonb,
            'properties', jsonb_build_object(
                'id', b.id,
                'ma_xa', b.ma_xa,
                'so_to', b.so_to,
                'tile_url', b.tile_url,
                'tile_version', b.tile_version,
                'min_zoom', b.min_zoom,
                'max_zoom', b.max_zoom,
                'trang_thai', b.trang_thai,
                'updated_at', b.updated_at
            )
        ) as feature
        from public.ban_do_nen b
        where b.geom && ST_MakeEnvelope(p_west, p_south, p_east, p_north, 4326)
          and (p_include_all or (b.trang_thai = 'ready' and b.kich_hoat))
        order by b.so_to
    ) features;
$$;

revoke all on function public.get_ban_do_nen_in_view(double precision, double precision, double precision, double precision, boolean) from public;
grant execute on function public.get_ban_do_nen_in_view(double precision, double precision, double precision, double precision, boolean) to service_role;

-- Tra cứu tờ bản đồ theo mã xã (+ số tờ tùy chọn) — dùng cho ô tìm kiếm
-- trên bản đồ chính và trang quản trị, không lọc theo khung nhìn/trạng
-- thái.
create or replace function public.get_ban_do_nen_by_ma_xa_so_to(
    p_ma_xa text,
    p_so_to integer default null
)
returns jsonb
language sql
stable
security definer
set search_path = public, extensions
as $$
    select jsonb_build_object(
        'type', 'FeatureCollection',
        'features', coalesce(jsonb_agg(feature), '[]'::jsonb)
    )
    from (
        select jsonb_build_object(
            'type', 'Feature',
            'id', b.id,
            'geometry', ST_AsGeoJSON(b.geom)::jsonb,
            'properties', jsonb_build_object(
                'id', b.id,
                'ma_xa', b.ma_xa,
                'so_to', b.so_to,
                'tile_url', b.tile_url,
                'tile_version', b.tile_version,
                'min_zoom', b.min_zoom,
                'max_zoom', b.max_zoom,
                'trang_thai', b.trang_thai,
                'updated_at', b.updated_at
            )
        ) as feature
        from public.ban_do_nen b
        where b.ma_xa = p_ma_xa
          and (p_so_to is null or b.so_to = p_so_to)
    ) features;
$$;

revoke all on function public.get_ban_do_nen_by_ma_xa_so_to(text, integer) from public;
grant execute on function public.get_ban_do_nen_by_ma_xa_so_to(text, integer) to service_role;


