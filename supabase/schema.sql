create or replace function public.ban_do_nen_set_bbox_from_geom()
returns trigger
language plpgsql
as $$
begin
    new.bbox_min_x := ST_XMin(new.geom);
    new.bbox_min_y := ST_YMin(new.geom);
    new.bbox_max_x := ST_XMax(new.geom);
    new.bbox_max_y := ST_YMax(new.geom);
    new.updated_at := now();
    return new;
end;
$$;

