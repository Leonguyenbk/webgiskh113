create index if not exists idx_nhom3_tien_do_lich_su_xa_time
    on public.nhom3_tien_do_lich_su (ma_xa, ghi_nhan_luc);

create or replace function public.refresh_nhom3_trang_thai_cache()
returns integer
language plpgsql
security definer
set search_path = public, extensions
-- Trước khi có cột du_lieu_gcn.nhom3_du_du_lieu (xem dưới), CTE
-- gcn_du_keys gọi _nhom3_gcn_du_du_lieu() (regex) cho TỪNG dòng
-- du_lieu_gcn MỖI LẦN refresh -> sau khi bảng lên ~1.9 triệu dòng
-- (nhom3_can_thu_thap) + du_lieu_gcn 734k dòng, đo thực tế 20+ phút, có
-- lúc statement_timeout 600s không kịp hủy. Đã chuyển sang đọc thẳng cột
-- boolean lưu sẵn (tính 1 lần qua trigger trg_nhom3_set_du_du_lieu khi
-- insert/update du_lieu_gcn, không tính lại mỗi lần refresh nữa) -> đo
-- lại còn ~92s ở quy mô hiện tại -> hạ statement_timeout về 180s.
set statement_timeout = '180s'
set work_mem = '512MB'
as $$
declare
    v_now timestamptz := now();
    v_rows integer;
begin
    -- Khoá theo phạm vi transaction: lần refresh thứ 2 chạy song song sẽ
    -- chờ ở đây, rồi rơi vào nhánh "vừa mới tính" bên dưới và thoát nhanh.
    perform pg_advisory_xact_lock(hashtext('refresh_nhom3_trang_thai_cache'));

    if exists (
        select 1 from public.nhom3_trang_thai_cache
        where computed_at > v_now - interval '1 minute'
    ) then
        select count(*) into v_rows from public.nhom3_trang_thai_cache;
        return v_rows;
    end if;

    -- UPSERT thay cho "delete + insert": không có DELETE trần (Supabase
    -- bật pg-safeupdate -> "DELETE requires a WHERE clause"), và người đọc
    -- luôn thấy 1 bộ đầy đủ (cũ hoặc mới), không có khoảng trống rỗng.
    insert into public.nhom3_trang_thai_cache
        (ma_xa, so_to, so_thua, ma_dinh_danh, la_nhom_1_2, da_thu_thap, co_nhap, computed_at)
    with
    -- MỌI thửa có ít nhất 1 dòng du_lieu_gcn, bất kể đủ dữ liệu hay không.
    -- da_thu_thap = co_nhap: ĐÃ BỎ yêu cầu "đạt chuẩn đủ dữ liệu"
    -- (nhom3_du_du_lieu) khỏi việc tính "đã làm" — thửa đã nhập biểu, có
    -- trong danh sách gửi xã, là tính đã làm luôn, không siết thêm điều
    -- kiện chất lượng nữa (yêu cầu người dùng). Cột nhom3_du_du_lieu vẫn
    -- giữ lại trên du_lieu_gcn để dùng cho mục đích khác nếu cần sau này.
    gcn_any_keys as (
        select distinct g.madvhc_soto_sothua
        from public.du_lieu_gcn g
    ),
    nhom12_keys as (
        select d.ma_xa, d.so_to, d.so_thua
        from public.dong_bo_du_lieu d
        where upper(trim(d.phan_loai_ke_hoach_2959)) in ('NHÓM 1', 'NHÓM 2')
    )
    select
        t.ma_xa, t.so_to, t.so_thua, t.ma_dinh_danh,
        (n12.ma_xa is not null) as la_nhom_1_2,
        (a.madvhc_soto_sothua is not null) as da_thu_thap,
        (a.madvhc_soto_sothua is not null) as co_nhap,
        v_now
    from public.nhom3_can_thu_thap t
    -- LEFT JOIN (trước là INNER) — thửa thuộc ranh dự án hoặc chưa có
    -- hình học (p.ma_xa is null) vẫn cần xét tới, vì có thể xã ĐÃ LỠ nhập
    -- biểu cho thửa đó (xem điều kiện where bên dưới) -> không bỏ thẳng
    -- khỏi cache nữa, chỉ bỏ khi KHÔNG có dữ liệu nhập (yêu cầu người dùng).
    left join public.thua_dat p
        on p.ma_xa = t.ma_xa and p.so_to = t.so_to and p.so_thua = t.so_thua
    -- Xã thuộc 1 dự án tổng thể khác (ghi chú ở nhom3_xa_ghi_chu, ví dụ
    -- Ea Ning/Ea Ktur/Dray Bhăng — Cư Kuin) KHÔNG đánh giá Nhóm 3 ở xã đó
    -- nữa, dù nhom3_can_thu_thap lỡ có nạp danh sách — loại NGAY TỪ ĐÂY
    -- (LEFT JOIN + gc.ma_xa is null, anti-join hiệu quả hơn NOT EXISTS
    -- tương quan khi bảng t đã lên tới hàng triệu dòng) để nhom3_tong_hop
    -- (nhánh ghi_chu, where not exists cache) tự hiện đúng dòng ghi chú,
    -- không bị đè bởi số liệu thật.
    left join public.nhom3_xa_ghi_chu gc
        on gc.ma_xa = t.ma_xa
    left join nhom12_keys n12
        on n12.ma_xa = t.ma_xa and n12.so_to = t.so_to and n12.so_thua = t.so_thua
    left join gcn_any_keys a
        on a.madvhc_soto_sothua = t.ma_xa || '_' || t.so_to::text || '_' || t.so_thua::text
    -- Thửa đã đánh dấu thuộc 1 ranh dự án (xem
    -- luu_ranh_du_an_va_danh_dau_nhom3) hoặc chưa có hình học trên bản đồ
    -- (p.ma_xa is null, chưa nhập GML) bình thường KHÔNG tính vào khối
    -- lượng Nhóm 3 cần gửi xã nữa -> loại khỏi cache. NGOẠI LỆ: nếu xã ĐÃ
    -- LỠ nhập biểu cho đúng thửa đó (a.madvhc_soto_sothua is not null) thì
    -- vẫn tính vào tổng + tính luôn cho xã (co_nhap/da_thu_thap ở trên tự
    -- động = true cho các dòng này) — ghi nhận công sức xã đã làm thay vì
    -- bỏ hẳn (yêu cầu người dùng, xem thêm nhom3_tong_hop bên dưới).
    -- ĐÃ REVERT loại đất tổ chức (p.ten_chu, _nhom3_la_dat_to_chuc) khỏi
    -- đây — đất tổ chức/đất công ích do UBND xã quản lý vẫn phải nhập biểu
    -- bình thường, chỉ nên phân biệt trên bản đồ (nếu cần), không loại
    -- khỏi đếm/danh sách "còn thiếu" (yêu cầu người dùng).
    where gc.ma_xa is null
      and (
            (not t.thuoc_du_an and p.ma_xa is not null)
            or a.madvhc_soto_sothua is not null
          )
    on conflict (ma_xa, so_to, so_thua) do update set
        ma_dinh_danh = excluded.ma_dinh_danh,
        la_nhom_1_2  = excluded.la_nhom_1_2,
        da_thu_thap  = excluded.da_thu_thap,
        co_nhap      = excluded.co_nhap,
        computed_at  = excluded.computed_at;

    get diagnostics v_rows = row_count;

    -- Dọn thửa không còn khớp (xoá khỏi nhom3_can_thu_thap hoặc không còn
    -- khớp thua_dat) — DELETE này CÓ mệnh đề WHERE.
    delete from public.nhom3_trang_thai_cache where computed_at < v_now;

    -- Ghi 1 lát cắt lịch sử theo xã (KHÔNG đè, mỗi lần refresh thêm 1 bộ
    -- dòng mới) — dùng để vẽ trend tốc độ xử lý theo thời gian. Tận dụng
    -- đúng lịch 2 giờ/lần đang chạy (WebGIS-RefreshNhom3Stats), không cần
    -- lịch/hạ tầng riêng cho việc ghi lịch sử.
    insert into public.nhom3_tien_do_lich_su (ma_xa, tong, da_nhom_1_2, da_thu_thap, con_thieu, ghi_nhan_luc)
    select
        ma_xa,
        count(*) as tong,
        count(*) filter (where la_nhom_1_2) as da_nhom_1_2,
        count(*) filter (where not la_nhom_1_2 and da_thu_thap) as da_thu_thap,
        count(*) filter (where not la_nhom_1_2 and not da_thu_thap) as con_thieu,
        v_now
    from public.nhom3_trang_thai_cache
    group by ma_xa;

    return v_rows;
end;
$$;

revoke all on function public.refresh_nhom3_trang_thai_cache() from public;
grant execute on function public.refresh_nhom3_trang_thai_cache() to service_role;

-- Ghi chú riêng theo xã cho trang "/nhom-3-con-thieu" — dùng cho xã
