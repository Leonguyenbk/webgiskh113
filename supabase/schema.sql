-- Nhận diện 9 NHÓM nguồn gốc sử dụng hợp lệ (khớp ý nghĩa với
-- NGUON_GOC_OPTIONS trong frontend/src/utils/nhom4Constants.js), KHÔNG so
-- khớp nguyên văn từng chữ — dữ liệu nạp từ file VPĐK/office cũ dùng rất
-- nhiều cách viết tắt/biến thể khác form Nhóm 4 (ví dụ nguyên 1 xã Ea Kly
-- dùng toàn "CNQ-KTT"/"CNQ-CTT" thay vì ghi đầy đủ, khiến match nguyên văn
-- ra 0 dù hồ sơ đã đủ). Chuẩn hoá bỏ dấu + viết thường rồi nhận theo từ
-- khoá đặc trưng của từng nhóm. Giá trị mơ hồ/khác nhóm (Khai hoang, NN/
-- UBND giao để quản lý, "Nhà nước cấp" không rõ loại...) CHỦ Ý vẫn coi là
-- chưa hợp lệ — các trường hợp này cần xử lý/phân loại lại riêng sau,
-- không phải lỗi của hàm này. Tách hàm riêng để dùng lại được cho cả
-- nguongoc1 lẫn nguongoc2.
create or replace function public._nhom3_nguon_goc_hop_le(gia_tri text)
returns boolean
language sql
immutable
set search_path = public, extensions
as $$
    with v as (
        select regexp_replace(
                 lower(extensions.unaccent(coalesce(gia_tri, ''))),
                 '\s+', ' ', 'g'
               ) as t
    )
    select
        t <> ''
        and (
            t ~ 'chuyen nhuong|sang nhuong|mua lai'
            or t ~ 'thua ke'
            or t ~ 'tang cho|cho tang|tang tu'
            or t ~ 'nha nuoc giao dat (khong|co) thu tien'
            or t ~ 'cho thue dat.*tra tien (hang nam|mot lan)'
            or t ~ 'cnq.{0,3}(ktt|ctt)'
            or (t ~ 'cong nhan' and t ~ 'thu tien')
            -- Đất Nhà nước giao để QUẢN LÝ (đất công ích/đất Nhà nước giao
            -- UBND xã quản lý) — nguồn gốc có thật, khác hẳn đất hộ gia
            -- đình/cá nhân ở các mục trên, trước đây không nằm trong danh
            -- sách nên bị chặn oan (xem backend/scratch_apply_*nguon_goc*).
            -- "nuo+c" chịu được lỗi gõ thừa nguyên âm (VD "nươớc" -> "nuooc").
            or t ~ '(nha nuo+c|nn) giao.{0,10}quan ly'
        )
    from v
$$;

revoke all on function public._nhom3_nguon_goc_hop_le(text) from public;
grant execute on function public._nhom3_nguon_goc_hop_le(text) to service_role;

