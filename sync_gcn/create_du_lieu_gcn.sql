-- An toàn chạy lại nếu bảng đã tồn tại từ trước (lúc chưa có cột này):
alter table public.du_lieu_gcn
  add column if not exists ngaysinh_chusudunghientai text;

create index if not exists idx_du_lieu_gcn_ma_nguon
  on public.du_lieu_gcn (ma_nguon);

create index if not exists idx_du_lieu_gcn_madvhc
  on public.du_lieu_gcn (madvhc);

create index if not exists idx_du_lieu_gcn_madvhc_soto_sothua
  on public.du_lieu_gcn (madvhc, soto, sothua);

create index if not exists idx_du_lieu_gcn_sophathanhgcn
  on public.du_lieu_gcn (sophathanhgcn);

alter table public.du_lieu_gcn enable row level security;

