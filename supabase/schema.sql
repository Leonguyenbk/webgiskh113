    tong_so_thua bigint,
    da_nhap_bieu bigint,
    computed_at timestamptz
)
language sql
stable
security definer
set search_path = public, extensions
as $$
    select c.ma_xa, c.tong_so_thua, c.da_nhap_bieu, c.computed_at
