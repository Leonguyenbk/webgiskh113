-- Trend tiến độ theo xã, đọc từ nhom3_tien_do_lich_su — mỗi lát cắt kèm
-- tốc độ xử lý (thửa/ngày) tính bằng hiệu "đã làm" (Nhóm 1/2 + đã thu
-- thập) so với lát cắt NGAY TRƯỚC của CÙNG xã, quy ra theo ngày (khoảng
-- cách thực giữa 2 lần ghi nhận có thể lệch khỏi đúng 3 giờ nếu service
-- dừng/khởi động lại, nên chia theo giây thực tế, không giả định cố định).
-- Lát cắt đầu tiên của mỗi xã không có lát trước -> toc_do_thua_ngay NULL.
-- p_tu/p_den lọc KHOẢNG HIỂN THỊ — tính lag() trên TOÀN BỘ lịch sử trước,
-- rồi mới cắt theo khoảng, để điểm đầu tiên trong khoảng vẫn tính đúng
-- tốc độ (dựa vào lát cắt ngay trước đó, có thể nằm ngoài khoảng p_tu).
drop function if exists public.nhom3_tien_do_trend(text, timestamptz);

create or replace function public.nhom3_tien_do_trend(
    p_ma_xa text default null,
    p_tu timestamptz default null,
    p_den timestamptz default null
)
returns jsonb
language sql
stable
security definer
set search_path = public, extensions
as $$
    with lich_su as (
        select
            h.ma_xa, xp.ten_xa, h.tong, h.da_nhom_1_2, h.da_thu_thap, h.con_thieu,
            (h.da_nhom_1_2 + h.da_thu_thap) as da_lam,
            h.ghi_nhan_luc
        from public.nhom3_tien_do_lich_su h
        left join public.danhsachxaphuong xp on xp.ma_xa = h.ma_xa
        where (p_ma_xa is null or h.ma_xa = p_ma_xa)
    ),
    voi_lat_truoc as (
        select
            *,
            lag(da_lam) over (partition by ma_xa order by ghi_nhan_luc) as da_lam_truoc,
            lag(ghi_nhan_luc) over (partition by ma_xa order by ghi_nhan_luc) as luc_truoc
        from lich_su
    )
    select coalesce(jsonb_agg(row_to_json(x) order by x.ma_xa, x.ghi_nhan_luc), '[]'::jsonb)
    from (
        select
            ma_xa, ten_xa, tong, da_nhom_1_2, da_thu_thap, con_thieu, da_lam, ghi_nhan_luc,
            case
                when luc_truoc is null or ghi_nhan_luc = luc_truoc then null
                else round(
                    (da_lam - da_lam_truoc) / (extract(epoch from (ghi_nhan_luc - luc_truoc)) / 86400.0)
                , 2)
            end as toc_do_thua_ngay
        from voi_lat_truoc
        where (p_tu is null or ghi_nhan_luc >= p_tu)
          and (p_den is null or ghi_nhan_luc <= p_den)
    ) x;
$$;

