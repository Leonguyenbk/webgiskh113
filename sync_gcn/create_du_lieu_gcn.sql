  -- đúng thứ tự cột B..BF — dữ liệu thật bắt đầu từ dòng 4, không phải
  -- dòng 3 như dự kiến ban đầu, và sheet có 57 cột chứ không phải 56 vì
  -- có thêm cột "Ngày sinh người sử dụng hiện tại"). Giữ kiểu text ở
  -- bản đầu để không mất số 0 đầu ở CCCD/mã định danh/số giấy tờ và
  -- tránh sai lệch định dạng.
  madvhc text,
  sophathanhgcn text,
  ngaycapgcn text,
  sovaosogcn text,
  tentochuc text,
  madinhdanhtochuc text,
  hovatenchusudung text,
  ngaythangnamsinh text,
  gioitinh text,
  sodinhdanhcanhan text,
  diachithuongtru text,
  phapnhantrengcn text,
  vaitrophapnhan text,
  tenchusudunghientai text,
  ngaysinh_chusudunghientai text,
  sodinhdanh_chusudunghientai text,
  diachi_chusudunghientai text,
  lydothaydoi text,
  madinhdanhthuadat text,
  soto_gcn text,
  sothua_gcn text,
  soto text,
  sothua text,
  diachi_thuadat text,
  dientichthuadat text,
  loaidat1 text,
  dientich1 text,
  nguongoc1 text,
  hinhthucsudung1 text,
  thoihansudung1 text,
  loaidat2 text,
  dientich2 text,
  nguongoc2 text,
  hinhthucsudung2 text,
  thoihansudung2 text,
